TRANSLATIONS: Mapping[str, Mapping[str, str]] = MappingProxyType({"zh-CN": MappingProxyType(_ZH), "en": MappingProxyType(_EN)})

def get_locale(state: Mapping[str, object]) -> str:
    value = state.get("locale", "zh-CN")
    return value if value in LOCALES else "zh-CN"

def set_locale(state: MutableMapping[str, object], locale: str) -> None:
    if locale not in LOCALES:
        raise ValueError(f"Unsupported locale: {locale!r}.")
    state["locale"] = locale

def t(key: str, *, locale: str = "zh-CN", **kwargs: object) -> str:
    if locale not in TRANSLATIONS:
        locale = "zh-CN"
    value = TRANSLATIONS[locale].get(key)
    if value is None:
        return f"⟦{key}⟧"
    try:
        return value.format(**kwargs)
    except (KeyError, ValueError):
        return f"⟦{key}⟧"
